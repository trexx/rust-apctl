#!/usr/bin/env bash
# Regenerates crates/apcfg/src/tz/zones.rs, the Olson name -> POSIX TZ table, from the
# host's IANA tz database (public domain): every zone and link tzdata.zi names (the
# canonical zones plus the `backward` links), except Factory, with the POSIX footer
# line of its TZif file. Run it after a tzdata update and review the diff:
#
#   scripts/gen-tz.sh                         # reads /usr/share/zoneinfo
#   ZONEINFO=/path/to/zoneinfo scripts/gen-tz.sh
set -euo pipefail

zi=${ZONEINFO:-/usr/share/zoneinfo}
cd "$(dirname "$0")/.."
out=crates/apcfg/src/tz/zones.rs
version=$(sed -n 's/^# version //p' "$zi/tzdata.zi")

# Main-format tzdata gives Ireland negative summer time (IST in winter is the standard
# time). Its rearguard form, which every libc reads the same way, is kept for it.
rearguard() {
  case $1 in
    Europe/Dublin | Eire) echo "GMT0IST,M3.5.0/1,M10.5.0" ;;
    *) return 1 ;;
  esac
}

{
  echo "// Generated by scripts/gen-tz.sh from tzdata $version; do not edit."
  echo
  echo "pub(super) const ZONES: &[(&str, &str)] = &["
  awk '$1 == "Z" { print $2 } $1 == "L" { print $3 }' "$zi/tzdata.zi" | grep -vx Factory | LC_ALL=C sort -u |
    while read -r name; do
      footer=$(rearguard "$name") || footer=$(tail -n 1 "$zi/$name")
      if [[ -z $footer || $footer == *[\"\\]* ]]; then
        echo "gen-tz: $name has no usable POSIX footer: '$footer'" >&2
        exit 1
      fi
      printf '    ("%s", "%s"),\n' "$name" "$footer"
    done
  echo "];"
} >"$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out ($(grep -c '^    (' "$out") zones, tzdata $version)"
